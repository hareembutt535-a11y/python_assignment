# Arithmetic operators
a = 10
b = 5
print("Arithmetic Operators")
print(a + b)
print(a - b)
print(a * b)
print(a / b)


#Logical Operators
print("Logical Operators")
print(a > 5 and b < 10)
print(a < 5 or b < 10)
print(not(a > 5))


#Assignment Operators
print("Assignment Operators")
x = 10
x  += 5
print(x)
x -= 3
print(x)

#Comparison Operators
print("Comparison Operators")
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)
